export type MessageKey = keyof typeof messages.bg

/**
 * The language is fixed by audience, not chosen by the user: the child's practice screen is Bulgarian
 * (with an opt-in Russian translation per problem), everything parents use is Russian.
 */
export const CHILD_LOCALE: Locale = 'bg'
export const PARENT_LOCALE: Locale = 'ru'

export function useLocale(locale: Locale) {
  const t = (key: MessageKey) => messages[locale][key]
  const pick = (text: LocalizedText) => text[locale]

  return { locale, t, pick }
}
